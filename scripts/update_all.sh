#!/bin/bash

# Скрипт полного обновления XVPN
# Обновляет и сервер, и клиент последовательно

set -e  # Оновить выполнение при ошибке

echo "=== Полное обновление XVPN ==="

# Проверка прав root для серверного обновления
if [ "$EUID" -eq 0 ]; then
    echo "Запуск обновления сервера..."
    ./scripts/update_server.sh
    echo "✅ Сервер успешно обновлен"
else
    echo "Предупреждение: Для обновления сервера требуются права root"
    echo "Пропускаем серверное обновление"
fi

echo ""
echo "Запуск обновления клиента..."
./scripts/update_client.sh
echo "✅ Клиент успешно обновлен"

echo ""
echo "=== Полное обновление XVPN завершено ==="
echo ""
echo "Рекомендуется:"
echo "1. Проверить работу сервера: curl -k https://localhost:8443/health"
echo "2. Запустить клиент для тестирования: ./xvpn-client"
echo "3. Запустить GUI клиента: ./xvpn-client-gui"